// frontend/scripts/draft-to-topics.mjs
//
// Turns a draft JSON (from import-mdn-topic.mjs) into a typed topics file,
// with image blocks wired to Vite asset imports.
//
// Usage:
//   node scripts/draft-to-topics.mjs <draft.json> <courseId> <fileName>
// Example:
//   node scripts/draft-to-topics.mjs scripts/output/html-draft.json html basicHtmlSyntax
//   -> src/content/topics/html/basicHtmlSyntax.ts (exports basicHtmlSyntaxTopics)

import fs from 'node:fs/promises';
import path from 'node:path';

const [, , draftPath, courseId, fileName] = process.argv;

if (!draftPath || !courseId || !fileName) {
  console.error('Usage: node scripts/draft-to-topics.mjs <draft.json> <courseId> <fileName>');
  process.exit(1);
}

const outFile = path.resolve('src/content/topics', courseId, `${fileName}.ts`);
const exportName = `${fileName}Topics`;

// The generated file gets hand-edited afterwards, so never overwrite it.
const exists = await fs.access(outFile).then(
  () => true,
  () => false
);
if (exists) {
  console.error(
    `Refusing to overwrite ${outFile}. Delete it first if you really want to regenerate.`
  );
  process.exit(1);
}

const topics = JSON.parse(await fs.readFile(draftPath, 'utf8'));

// grumpy-cat-small.png -> grumpyCatSmall
function toIdentifier(filename) {
  const camel = filename
    .replace(/\.[^.]+$/, '')
    .replace(/[^a-zA-Z0-9]+(.)?/g, (_, c) => (c ? c.toUpperCase() : ''));
  const ident = camel.charAt(0).toLowerCase() + camel.slice(1);
  return /^[0-9]/.test(ident) ? `img${ident}` : ident;
}

const imports = new Map(); // filename -> identifier
function importFor(filename) {
  if (imports.has(filename)) return imports.get(filename);
  const base = toIdentifier(filename);
  let ident = base;
  let n = 2;
  while ([...imports.values()].includes(ident)) ident = `${base}${n++}`;
  imports.set(filename, ident);
  return ident;
}

const record = {};
for (const topic of topics) {
  record[topic.id] = {
    id: topic.id,
    heading: topic.heading,
    blocks: topic.blocks.map((block) =>
      block.type === 'image'
        ? {
            type: 'image',
            src: `__IMPORT__${importFor(block.filename)}__`,
            alt: block.alt,
          }
        : block
    ),
    sourceUrl: topic.sourceUrl,
  };
}

// Turn the "__IMPORT__name__" placeholder strings into bare identifiers
const body = JSON.stringify(record, null, 2).replace(/"__IMPORT__(\w+)__"/g, '$1');

const importLines = [...imports].map(
  ([filename, ident]) => `import ${ident} from '../../assets/${courseId}/${filename}';`
);

const source = `// Generated by scripts/draft-to-topics.mjs from an MDN import, then hand-reviewed.
// Content adapted from MDN Web Docs (https://developer.mozilla.org), licensed CC BY-SA.
import type { ContentTopic } from '../../types';
${importLines.join('\n')}

export const ${exportName}: Record<string, ContentTopic> = ${body};
`;

await fs.mkdir(path.dirname(outFile), { recursive: true });
await fs.writeFile(outFile, source);

console.log(`Wrote ${outFile} (${topics.length} topics, ${imports.size} image import(s)).`);
console.log(
  `Now add it to src/content/topics/${courseId}/index.ts and run prettier on the new file.`
);
